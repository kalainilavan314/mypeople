import type { ReactNode } from 'react';

/**
 * Outline icons for the dashboard's modules, shared by the sidebar and the overview, and the
 * accent colour of each module's section (the same colours as the sidebar's sections).
 */

export type ModuleIcon = (props: { className?: string }) => ReactNode;

const SECTION_HREFS: readonly { accent: Accent; hrefs: readonly string[] }[] = [
  { accent: 'indigo', hrefs: ['/verification', '/appeals', '/duplicates', '/membership', '/renewals', '/members', '/access', '/access-reviews'] },
  {
    accent: 'green',
    hrefs: [
      '/cases', '/support', '/volunteering', '/volunteer-assignments', '/development', '/surveys', '/learning', '/promises',
      '/scorecards', '/town-halls', '/budgeting', '/committees', '/livelihood', '/representatives', '/disaster',
      '/blood-requests', '/field', '/roster',
    ],
  },
  { accent: 'purple', hrefs: ['/events', '/gallery', '/messages', '/publishing', '/moderation', '/elections', '/assistant', '/ai-models'] },
];

export type Accent = 'purple' | 'blue' | 'green' | 'red' | 'orange' | 'teal' | 'indigo' | 'gold' | 'pink';

/** Tailwind classes per accent, written out in full so Tailwind finds them. */
export const ACCENT_TILE: Readonly<Record<Accent, string>> = {
  purple: 'bg-accent-purple text-on-primary',
  blue: 'bg-accent-blue text-on-primary',
  green: 'bg-accent-green text-on-primary',
  red: 'bg-accent-red text-on-primary',
  orange: 'bg-accent-orange text-on-primary',
  teal: 'bg-accent-teal text-on-primary',
  indigo: 'bg-accent-indigo text-on-primary',
  gold: 'bg-accent-gold text-on-primary',
  pink: 'bg-accent-pink text-on-primary',
};

/** The accent of a module's sidebar section; finance and administration are orange. */
export function moduleAccent(href: string): Accent {
  const path = '/' + href.split('?')[0].split('/')[1];
  return SECTION_HREFS.find((section) => section.hrefs.includes(path))?.accent ?? 'orange';
}

