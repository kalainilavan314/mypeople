// Runs the Express API's own auth code (server/src/lib.js and bcryptjs from
// server/node_modules) so the Python tests can check that
// services/api produces and accepts exactly the same values.
//
// Regenerate the fixed vectors (reads vectors-request.json, writes
// auth_vectors.json next to this file):
//   node tests/express/auth_helpers.mjs --write-vectors
//
// Live checks: one JSON request on stdin, JSON on stdout. JWT_SECRET and
// NIC_PEPPER must be set in the environment; the tests pass test-only values.
//   {"command": "sign", "memberId": ..., "sessionVersion": ...}   a token signed now
//   {"command": "verify", "token": ...}             the claims, or {"error": ...}
//   {"command": "bcrypt-compare", "password": ..., "hash": ...}   true or false
//   {"command": "bcrypt-hash", "password": ...}     a hash made as the Express signup does
//   {"command": "check-login", "identifier": ..., "ip": ...}
//                                                   throttle.js checkLogin against DATABASE_URL
//   {"command": "session-live", "token": ...}       sessions.js sessionIsLive against DATABASE_URL
import fs from 'node:fs';
import { createRequire } from 'node:module';

const writeVectors = process.argv[2] === '--write-vectors';
const vectorsRequest = writeVectors
  ? JSON.parse(fs.readFileSync(new URL('./vectors-request.json', import.meta.url), 'utf8'))
  : null;

if (writeVectors) {
  // lib.js reads its secrets when it is imported, so set them first.
  process.env.JWT_SECRET = vectorsRequest.secrets.jwtSecret;
  process.env.NIC_PEPPER = vectorsRequest.secrets.nicPepper;
}
if (!process.env.JWT_SECRET || !process.env.NIC_PEPPER) {
  // lib.js would otherwise fall back to its dev values without saying so.
  console.error('JWT_SECRET and NIC_PEPPER must be set');
  process.exit(2);
}

const libUrl = new URL('../../../../server/src/lib.js', import.meta.url);
const requireFromServer = createRequire(libUrl);
const bcrypt = requireFromServer('bcryptjs');
const lib = await import(libUrl);

// A fixed clock makes the signed tokens reproducible. jsonwebtoken reads
// Date.now() for "iat" and derives "exp" from it.
function atFixedTime(epochSeconds, fn) {
  const realNow = Date.now;
  Date.now = () => epochSeconds * 1000;
  try {
    return fn();
  } finally {
    Date.now = realNow;
  }
}

function vectors({ secrets, nics, passwords, memberId, issuedAt }) {
  const longTamil = 'தமிழ்'.repeat(6); // 30 code points, 90 UTF-8 bytes
  const longTamilHash = bcrypt.hashSync(longTamil, 10);
  return {
    note: 'Generated by auth_helpers.mjs --write-vectors from server/src/lib.js. Test-only secrets.',
    secrets,
    nicHashes: nics.map((nic) => ({ nic, hash: lib.nicHash(nic) })),
    passwords: [
      ...passwords.map((password) => ({ password, hash: bcrypt.hashSync(password, 10), matches: true })),
      { password: longTamil, hash: longTamilHash, matches: true },
      // Only the first 72 bytes count: a password that differs after byte 72
      // still matches, and Python must agree for existing members.
      { password: longTamil.slice(0, 24) + 'different ending', hash: longTamilHash, matches: true },
      { password: 'wrong password', hash: longTamilHash, matches: false },
    ],
    // Signed at a fixed past time, so these expire: tests compare them byte for
    // byte with Python-signed tokens instead of verifying them against the clock.
    tokens: {
      issuedAt,
      memberId,
      signed: [0, 3].map((sessionVersion) => ({
        sessionVersion,
        token: atFixedTime(issuedAt, () => lib.signToken(memberId, sessionVersion)),
      })),
    },
  };
}

async function checkLogin({ identifier, ip }) {
  // Imported only here: db.js opens a connection pool to DATABASE_URL.
  const { checkLogin } = await import(new URL('../../../../server/src/throttle.js', import.meta.url));
  const { pool } = await import(new URL('../../../../server/src/db.js', import.meta.url));
  try {
    return await checkLogin(identifier, ip);
  } finally {
    await pool.end();
  }
}

async function sessionLive({ token }) {
  const { sessionIsLive } = await import(new URL('../../../../server/src/sessions.js', import.meta.url));
  const { pool } = await import(new URL('../../../../server/src/db.js', import.meta.url));
  try {
    return { live: await sessionIsLive(pool, lib.verifyToken(token)) };
  } finally {
    await pool.end();
  }
}

async function run(request) {
  switch (request.command) {
    case 'check-login':
      return checkLogin(request);
    case 'session-live':
      return sessionLive(request);
    case 'sign':
      return { token: lib.signToken(request.memberId, request.sessionVersion) };
    case 'verify':
      try {
        return { claims: lib.verifyToken(request.token) };
      } catch (error) {
        return { error: error.name };
      }
    case 'bcrypt-compare':
      return { matches: bcrypt.compareSync(request.password, request.hash) };
    case 'bcrypt-hash':
      return { hash: bcrypt.hashSync(request.password, 10) };
    default:
      throw new Error(`unknown command: ${request.command}`);
  }
}

if (writeVectors) {
  const target = new URL('./auth_vectors.json', import.meta.url);
  fs.writeFileSync(target, JSON.stringify(vectors(vectorsRequest), null, 2) + '\n', 'utf8');
  console.log('wrote auth_vectors.json');
} else {
  const text = fs.readFileSync(0, 'utf8');
  process.stdout.write(JSON.stringify(await run(JSON.parse(text))) + '\n');
}
